import { lazy, type ComponentType } from 'react'

// Halaman di dalam aplikasi dimuat saat dibuka (code splitting): Dashboard tidak lagi menunggu kode 30 halaman lain.
// Login & landing tetap langsung (halaman pertama yang dibuka tanpa login).
const satu = <M,>(muat: () => Promise<M>, ambil: (m: M) => ComponentType) => lazy(() => muat().then((m) => ({ default: ambil(m) })))
